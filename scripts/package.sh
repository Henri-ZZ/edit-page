#!/usr/bin/env bash
#
# Builds the Edit Page store artifacts.
#
# One run produces one zip per distribution channel, each with its own
# build-injected `distribution` value. The channel is build-owned and is never
# inferred at runtime: an Edge user may have installed from the Chrome Web
# Store, so the running browser says nothing about the package's origin.
#
#   ./scripts/package.sh          # Chrome Web Store + Edge Add-ons
#   ./scripts/package.sh cws      # Chrome Web Store only
#   ./scripts/package.sh edge     # Edge Add-ons only
#
# The injection happens inside a temporary staging copy, so the repository (and
# the unpacked development build) keeps the committed `development` value.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "$0")/.." && pwd)"
RELEASE_DIR="$ROOT_DIR/dist"
MANIFEST_PATH="$ROOT_DIR/manifest.json"
DISTRIBUTION_FILE="telemetry-distribution.js"
DEFAULT_CHANNELS=("cws" "edge")

# Everything that ships inside the extension. A missing entry fails the build.
SHIP_PATHS=(
  _locales
  assets
  background
  content
  icons
  i18n
  offscreen
  options
  popup
  public
  license.js
  shared.js
  telemetry.js
  "$DISTRIBUTION_FILE"
  manifest.json
)

usage() {
  echo "usage: $(basename "$0") [channel ...]" >&2
  echo "       channels: cws (Chrome Web Store), edge (Edge Add-ons), direct, development" >&2
  echo "       default:  ${DEFAULT_CHANNELS[*]}" >&2
}

distribution_for() {
  case "$1" in
    cws) printf 'cws' ;;
    edge) printf 'edge' ;;
    direct) printf 'direct' ;;
    development) printf 'development' ;;
    *) return 1 ;;
  esac
}

if [[ ! -f "$MANIFEST_PATH" ]]; then
  echo "[package] manifest.json not found" >&2
  exit 1
fi

VERSION="$(node -e "
  const fs = require('fs');
  const manifest = JSON.parse(fs.readFileSync(process.argv[1], 'utf8'));
  if (!manifest.version) {
    console.error('[package] manifest.json version is missing');
    process.exit(1);
  }
  process.stdout.write(String(manifest.version));
" "$MANIFEST_PATH")"

channels=("$@")
if [[ ${#channels[@]} -eq 0 ]]; then
  channels=("${DEFAULT_CHANNELS[@]}")
fi

for channel in "${channels[@]}"; do
  if ! distribution_for "$channel" >/dev/null; then
    echo "[package] unknown channel: $channel" >&2
    usage
    exit 1
  fi
done

echo "[package] Root:     $ROOT_DIR"
echo "[package] Version:  $VERSION"
echo "[package] Channels: ${channels[*]}"

mkdir -p "$RELEASE_DIR"

STAGE_DIR=""
cleanup() {
  if [[ -n "$STAGE_DIR" && -d "$STAGE_DIR" ]]; then
    rm -rf "$STAGE_DIR"
  fi
}
trap cleanup EXIT

for channel in "${channels[@]}"; do
  distribution="$(distribution_for "$channel")"
  zip_path="$RELEASE_DIR/editpage-${VERSION}-${channel}.zip"

  STAGE_DIR="$(mktemp -d)"
  for path in "${SHIP_PATHS[@]}"; do
    if [[ ! -e "$ROOT_DIR/$path" ]]; then
      echo "[package] missing file: $path" >&2
      exit 1
    fi
    cp -R "$ROOT_DIR/$path" "$STAGE_DIR/"
  done

  # The only file that differs between artifacts.
  printf '// Generated by scripts/package.sh. Do not edit in staged builds.\nexport const DISTRIBUTION = "%s";\n' \
    "$distribution" > "$STAGE_DIR/$DISTRIBUTION_FILE"

  rm -f "$zip_path"
  ( cd "$STAGE_DIR" && zip -qr "$zip_path" . )

  # Artifact check: read the injected value back out of the zip that is about to
  # be uploaded, so a mis-packaged channel fails the build instead of shipping
  # wrong analytics data.
  packaged="$(unzip -p "$zip_path" "$DISTRIBUTION_FILE" | sed -n 's/.*"\([a-z_]*\)".*/\1/p' | tail -n 1)"
  if [[ "$packaged" != "$distribution" ]]; then
    echo "[package] injection check failed for $channel (expected '$distribution', found '$packaged')" >&2
    exit 1
  fi

  file_count="$(unzip -l "$zip_path" | tail -n 1 | awk '{print $2}')"
  echo "[package] $channel: distribution=$packaged, files=$file_count"
  echo "[package]   -> $zip_path"

  rm -rf "$STAGE_DIR"
  STAGE_DIR=""
done

echo "[package] Done"
